// ==================== 尺度系统（单一比例）====================
// 只有这一个比例：1 像素 = 1 米（恒定，不随缩放变）
//
//   星球 2500000 px × 1 = 2500 km  ✅
//   部件 1 格 = 7 px × 1 = 7 m（默认船 14 m 宽 × 49 m 高，正常火箭大小）
//
// 想改尺度只改这一个数：它同时决定飞船大小和星球大小。
// 【1 px = 1 m】以前是 1 px = 50 m，结果飞船在物理世界里高达 2450 m
// （49 px × 50 m），几十米/秒相对这么大的船简直没动，屏幕上每秒不到 1 像素。
// SFS 的手感是「船几十米高、速度几十米/秒，屏幕上看得到明显移动」——
// 那正是 1 px ≈ 1 m。所以这里改成 1。
//
// 改这一个数，下面这些全部跟着自动换算（它们都用 M_PER_PX）：
//   引力 G0_PX = g / M_PER_PX
//   星球像素半径、大气标高、距离/速度显示……
// 唯独「像素制」的力（推力、阻力）要手动跟着缩放，见各自的注释。
export const M_PER_PX = 1;               // 全局唯一比例：1 px = 1 m

export const PLANET_RADIUS_KM = 2500;    // 星球真实半径 2500 km
export const PLANET_RADIUS_M = PLANET_RADIUS_KM * 1000;
export const ATMO_TOP_KM = 120;          // 大气顶 120 km（≈5 个标高，参考线不是物理墙）
export const ATMO_TOP_M = ATMO_TOP_KM * 1000;

// 兼容旧名字：物理与换算都用这一个值
export const PHYS_M_PER_PX = M_PER_PX;
export const DIST_M_PER_PX = M_PER_PX;   // 距离显示同尺度


// 表面引力（米制，唯一数据源）
// 3.71 m/s² 是火星表面重力，配合半径 2500 km：
//   逃逸速度 √(2×3.71×2.5e6) = 4307 m/s，充分留住 O₂/N₂ 大气；
//   密度 3g/(4πGR) = 5.31 g/cm³，落在真实岩石行星范围。
// 关键收益：关机后减速时间 ≈ v/g，比 1.35 时快 2.75 倍。
export const SURFACE_GRAVITY_MS2 = 3.71;
// 换算成像素加速度，供物理使用：a_px = a_m / M_PER_PX
export const G0_PX = SURFACE_GRAVITY_MS2 / M_PER_PX;   // = 3.71 px/s²（1px = 1m）


