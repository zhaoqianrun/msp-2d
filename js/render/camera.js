// ==== 视角控制 ====
// 双尺度缩放范围：
//   zoom = 1.0    -> 1 px = 5 cm   （贴地，飞船 49 px 看得清）
//   zoom = 0.001  -> 1 px = 50 m   （星球 20000 px 半径，能看全）
// 跨度正好 1000 倍，覆盖「从地面到看全整个星球」
// minZoom 要能让整个星球装进屏幕：半径 2,500,000 px × zoom ≈ 250 px
// 所以 minZoom 取 1e-4。maxZoom 12 时飞船 49 px 会放大到 588 px，够近。
export const camera = { x: 0, y: 0, zoom: 1.0, minZoom: 0.0001, maxZoom: 12.0 };

